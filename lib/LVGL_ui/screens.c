lv_obj_t *tick_value_change_obj;

static void event_handler_cb_drone_dashboard_obj12(lv_event_t *e) {
    lv_event_code_t event = lv_event_get_code(e);
    void *flowState = lv_event_get_user_data(e);
    (void)flowState;
    
    if (event == LV_EVENT_VALUE_CHANGED) {
        lv_obj_t *ta = lv_event_get_target_obj(e);
        if (tick_value_change_obj != ta) {
            bool value = lv_obj_has_state(ta, LV_STATE_CHECKED);
            assignBooleanProperty(flowState, 16, 3, value, "Failed to assign Checked state");
        }
    }
}

static void event_handler_cb_drone_radio_setup_scan_toggle(lv_event_t *e) {
    lv_event_code_t event = lv_event_get_code(e);
    void *flowState = lv_event_get_user_data(e);
    (void)flowState;
    
    if (event == LV_EVENT_VALUE_CHANGED) {
        if (lv_obj_has_state(lv_event_get_target_obj(e), LV_STATE_CHECKED)) {
            e->user_data = (void *)0;
            flowPropagateValueLVGLEvent(flowState, 2, 0, e);
        }
    }
    if (event == LV_EVENT_VALUE_CHANGED) {
        if (!lv_obj_has_state(lv_event_get_target_obj(e), LV_STATE_CHECKED)) {
            e->user_data = (void *)0;
            flowPropagateValueLVGLEvent(flowState, 2, 1, e);
        }
    }
}

